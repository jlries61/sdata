import os
def w(n,s): open(n,'w').write(s)
w('g_parens.cmd','REPEAT 1\nLET X = '+'('*100000+'1'+')'*100000+'\nPRINT X\nRUN\n')
w('g_unary.cmd','REPEAT 1\nLET X = '+'-'*200000+'1\nPRINT X\nRUN\n')
w('g_not.cmd','REPEAT 1\nLET X = '+'NOT '*100000+'1\nPRINT X\nRUN\n')
w('g_plus.cmd','REPEAT 1\nLET X = 1'+'+1'*300000+'\nPRINT X\nRUN\n')
w('g_pow.cmd','REPEAT 1\nLET X = 1'+'**1'*100000+'\nPRINT X\nRUN\n')
w('g_calls.cmd','REPEAT 1\nLET X = '+'ABS('*50000+'1'+')'*50000+'\nPRINT X\nRUN\n')
w('g_if.cmd','REPEAT 1\n'+'IF 1 THEN\n'*20000+'PRINT 1\n'+'END IF\n'*20000+'RUN\n')
w('g_for.cmd','REPEAT 1\n'+''.join(f'FOR I{i} = 1 TO 1\n' for i in range(5000))+'PRINT 1\n'+'NEXT\n'*5000+'RUN\n')
w('g_longstr.cmd','REPEAT 1\nLET X$ = "'+'a'*5000000+'"\nPRINT LEN(X$)\nRUN\n')
w('g_longid.cmd','REPEAT 1\nLET '+'A'*1000000+' = 1\nPRINT 1\nRUN\n')
w('g_manyvars.cmd','REPEAT 1\n'+''.join(f'LET V{i} = {i}\n' for i in range(20000))+'PRINT V19999\nRUN\n')
w('g_strcat.cmd','REPEAT 1\nLET X$ = "ab"\nFOR I = 1 TO 30\nLET Y$ = X$ + X$\nNEXT\nPRINT LEN(Y$)\nRUN\n')
