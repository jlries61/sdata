import codecs
d='csv/'
def w(n,b):
    open(d+n,'wb').write(b if isinstance(b,bytes) else b.encode())
w('empty.csv',b'')
w('nl_only.csv',b'\n\n\n')
w('hdr_only.csv','a,b,c\n')
w('hdr_nonl.csv','a,b,c')
w('bom.csv',codecs.BOM_UTF8+b'a,b\n1,2\n')
w('utf16le.csv',codecs.BOM_UTF16_LE+'a,b\n1,2\n3,4\n'.encode('utf-16-le'))
w('utf16be.csv',codecs.BOM_UTF16_BE+'a,b\n1,2\n3,4\n'.encode('utf-16-be'))
w('utf16nobom.csv','a,b\n1,2\n3,4\n'.encode('utf-16-le'))
w('latin1.csv',b'name$,v\ncaf\xe9,1\nna\xefve,2\n')
w('badutf8.csv',b'name$,v\n\xff\xfe\xfd,1\n\xc3\x28,2\n')
w('crlf.csv','a,b\r\n1,2\r\n3,4\r\n')
w('cr.csv','a,b\r1,2\r3,4\r')
w('mixed_eol.csv','a,b\r\n1,2\n3,4\r5,6\n')
w('embnl.csv','a$,b\n"line1\nline2",1\n"x,y",2\n"he said ""hi""",3\n')
w('unbal.csv','a$,b\n"abc,1\n2,3\n')
w('ragged.csv','a,b,c\n1,2\n1,2,3,4\n5\n,,\n')
w('dupcols.csv','a,a,b\n1,2,3\n')
w('onecol.csv','a\n1\n2\n.\n')
w('nul.csv',b'a,b\n1,\x002\n3,4\n')
w('nul2.csv',b'a$,b\nx\x00y,2\n')
w('numfmt.csv','a\n1e5\n0x10\n+5\n1,000\nNaN\ninf\n-\n 5 \n007\n1_000\n.5\n5.\n1e\n--5\n1d5\n')
w('numfmt2.csv','a\n1e5\n+5\n 5 \n007\n.5\n5.\n-0\n')
w('inttypes.csv','a%,b\n1,1\n2.5,2\n9223372036854775808,3\n-9223372036854775809,4\nabc,5\n')
w('trailing_dlm.csv','a,b,\n1,2,\n3,4,\n')
w('emptyhdr.csv',',b,\n1,2,3\n')
w('spaces_hdr.csv','first name, last-name ,x.y,AS,1abc,a$b,\n1,2,3,4,5,6,7\n')
w('longhdr.csv',','.join('c%d'%i for i in range(5000))+'\n'+','.join(str(i) for i in range(5000))+'\n')
w('longname.csv','A'*200+',B\n1,2\n')
w('longstr.csv','a$,b\n'+'x'*100000+',1\n')
w('tab.csv','a\tb\n1\t2\n')
w('semi.csv','a;b\n1,5;2\n')
w('allmissing.csv','a,b\n,\n,\n.,.\n')
w('blankmid.csv','a,b\n1,2\n\n3,4\n   \n5,6\n')
w('unicode.csv','név$,ñ\nÅngström,1\n日本語,2\n😀,3\n')
w('hugenum.csv','a\n1e308\n1e309\n-1e309\n4.9e-324\n1e-400\n12345678901234567890123\n')
